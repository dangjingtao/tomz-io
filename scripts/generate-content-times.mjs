import { execFileSync } from "node:child_process";
import { existsSync, mkdirSync, readdirSync, writeFileSync } from "node:fs";
import { dirname, relative, resolve } from "node:path";

const root = process.cwd();
const pagesRoot = resolve(root, "src/pages");
const outputPath = resolve(root, "src/content/content-times.generated.ts");

function markdownFiles(directory) {
  if (!existsSync(directory)) return [];
  return readdirSync(directory, { withFileTypes: true }).flatMap((entry) => {
    const path = resolve(directory, entry.name);
    return entry.isDirectory()
      ? markdownFiles(path)
      : entry.name.endsWith(".md") && !/^README\.md$/i.test(entry.name)
        ? [path]
        : [];
  });
}

function runGit(args, { quiet = false } = {}) {
  try {
    return execFileSync("git", args, {
      cwd: root,
      encoding: "utf8",
      stdio: ["ignore", "pipe", quiet ? "ignore" : "pipe"],
    }).trim();
  } catch (error) {
    if (quiet) return "";
    throw error;
  }
}

const shallow = runGit(["rev-parse", "--is-shallow-repository"], { quiet: true });
if (shallow === "true") {
  const message =
    "Content time generation requires complete Git history. Use a full clone or actions/checkout with fetch-depth: 0.";
  if (process.env.CI) {
    console.error(message);
    process.exit(1);
  }
  console.warn(`Warning: ${message}`);
}

const history = {};
for (const file of markdownFiles(pagesRoot)) {
  const repositoryPath = relative(root, file).replace(/\\/g, "/");
  const sourcePath = relative(pagesRoot, file).replace(/\\/g, "/");
  const raw = runGit(
    ["log", "--follow", "--format=%cI", "--", repositoryPath],
    { quiet: true },
  );
  const commitTimes = [...new Set(raw.split(/\r?\n/).map((item) => item.trim()).filter(Boolean))]
    .filter((value) => !Number.isNaN(Date.parse(value)))
    .sort((left, right) => Date.parse(right) - Date.parse(left));

  history[sourcePath] = {
    commitTimes,
    latestCommitAt: commitTimes[0],
    firstCommitAt: commitTimes.at(-1),
  };
}

const content = `// Generated by scripts/generate-content-times.mjs. Do not edit by hand.\n\nexport type GeneratedContentGitHistoryEntry = {\n  readonly commitTimes: readonly string[];\n  readonly latestCommitAt?: string;\n  readonly firstCommitAt?: string;\n};\n\nexport const contentGitHistory: Readonly<Record<string, GeneratedContentGitHistoryEntry>> = ${JSON.stringify(history, null, 2)};\n`;

mkdirSync(dirname(outputPath), { recursive: true });
writeFileSync(outputPath, content, "utf8");
console.log(
  `Content Git time index generated: ${Object.keys(history).length} Markdown files -> ${relative(root, outputPath)}`,
);
